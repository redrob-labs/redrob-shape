"""Generate checked-in Rust dependency inventory and license-text artifacts."""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

_LICENSE_PREFIXES = ("LICENSE", "COPYING", "NOTICE", "AUTHORS")


def _metadata(manifest: Path, cargo: str) -> dict:
    command = [
        cargo,
        "metadata",
        "--locked",
        "--format-version=1",
        "--manifest-path",
        str(manifest),
    ]
    completed = subprocess.run(command, check=True, capture_output=True, text=True)
    return json.loads(completed.stdout)


def _dependency_packages(metadata: dict) -> list[dict]:
    root_id = metadata["resolve"]["root"]
    resolved_ids = {node["id"] for node in metadata["resolve"]["nodes"]}
    return sorted(
        (
            package
            for package in metadata["packages"]
            if package["id"] in resolved_ids and package["id"] != root_id
        ),
        key=lambda package: (package["name"].casefold(), package["version"], package["id"]),
    )


def _license_files(package: dict) -> list[Path]:
    package_directory = Path(package["manifest_path"]).resolve().parent
    candidates = {
        path.resolve()
        for path in package_directory.iterdir()
        if path.is_file() and path.name.upper().startswith(_LICENSE_PREFIXES)
    }
    license_file = package.get("license_file")
    if license_file:
        candidate = (package_directory / license_file).resolve()
        if candidate.is_file() and candidate.is_relative_to(package_directory):
            candidates.add(candidate)
    return sorted(candidates, key=lambda path: path.name.casefold())


def _generate_inventory(packages: list[dict]) -> str:
    grouped = defaultdict(list)
    for package in packages:
        expression = package.get("license")
        if not expression:
            raise RuntimeError(f"dependency package has no license expression: {package['name']}")
        grouped[expression].append(f"{package['name']} {package['version']}")

    lines = [
        "<!--",
        "SPDX-FileCopyrightText: 2026 Redrob Labs",
        "",
        "SPDX-License-Identifier: GPL-3.0-or-later",
        "-->",
        "",
        "# Rust third-party dependency inventory",
        "",
        "This inventory and the checked-in [`THIRD_PARTY-LICENSES.txt`](THIRD_PARTY-LICENSES.txt) bundle are generated from `Cargo.lock` with `cargo metadata --locked`. Regenerate and verify both with `tools/generate_third_party_licenses.py` whenever locked dependencies change.",
        "",
    ]
    for expression in sorted(grouped, key=str.casefold):
        lines.extend((f"### `{expression}`", "", ", ".join(grouped[expression]), ""))
    return "\n".join(lines).rstrip() + "\n"


def _generate_license_bundle(packages: list[dict]) -> str:
    sections = [
        "REDROB REBLEND AGENT — THIRD-PARTY LICENSE TEXTS",
        "",
        "Generated deterministically from Cargo.lock by",
        "intern/redrob_agent/tools/generate_third_party_licenses.py.",
        "Do not edit this file manually.",
        "",
    ]
    missing = []
    for package in packages:
        license_files = _license_files(package)
        if not license_files:
            missing.append(f"{package['name']} {package['version']}")
            continue
        for license_path in license_files:
            heading = f"{package['name']} {package['version']} — {license_path.name}"
            body = license_path.read_text(encoding="utf-8", errors="replace").rstrip()
            sections.extend(("=" * 80, heading, "=" * 80, body, ""))
    if missing:
        raise RuntimeError("dependency packages without license or notice files: " + ", ".join(missing))
    return "\n".join(sections).rstrip() + "\n"


def generate(manifest: Path, cargo: str) -> tuple[str, str]:
    packages = _dependency_packages(_metadata(manifest, cargo))
    return _generate_inventory(packages), _generate_license_bundle(packages)


def _matches(path: Path, expected: str) -> bool:
    return path.is_file() and path.read_text(encoding="utf-8") == expected


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--cargo", default="cargo")
    parser.add_argument(
        "--manifest-path",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "Cargo.toml",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "THIRD_PARTY-LICENSES.txt",
    )
    parser.add_argument(
        "--inventory",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "THIRD_PARTY.md",
    )
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    try:
        inventory, bundle = generate(args.manifest_path.resolve(), args.cargo)
        if args.check:
            stale = [
                path
                for path, expected in ((args.inventory, inventory), (args.output, bundle))
                if not _matches(path, expected)
            ]
            for path in stale:
                print(f"out of date: {path}", file=sys.stderr)
            return bool(stale)
        args.inventory.write_text(inventory, encoding="utf-8")
        args.output.write_text(bundle, encoding="utf-8")
    except (OSError, KeyError, RuntimeError, subprocess.CalledProcessError, json.JSONDecodeError) as exc:
        print(f"license generation failed: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
